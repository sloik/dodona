"""Generate Unicode 15.1 tables from the official UCD files."""
import hashlib
import pathlib
import sys

root = pathlib.Path(sys.argv[1])
names = ['UnicodeData.txt', 'CompositionExclusions.txt', 'CaseFolding.txt', 'DerivedNormalizationProps.txt', 'NormalizationTest.txt']
files = {n: (root / n).read_bytes() for n in names}
assigned, ccc, decomp = [], {}, {}
first = None
for line in files[names[0]].decode().splitlines():
    f = line.split(';'); cp = int(f[0], 16)
    if f[1].endswith(', First>'):
        first = cp
    elif f[1].endswith(', Last>'):
        assigned.append((first, cp)); first = None
    else:
        assigned.append((cp, cp))
    if int(f[3]): ccc[cp] = int(f[3])
    if f[5] and not f[5].startswith('<'):
        decomp[cp] = [int(x, 16) for x in f[5].split()]
merged = []
for a, b in assigned:
    if merged and a <= merged[-1][1] + 1: merged[-1] = (merged[-1][0], b)
    else: merged.append((a, b))
excluded = set()
for line in files['DerivedNormalizationProps.txt'].decode().splitlines():
    s = line.split('#')[0].strip().split(';')
    if len(s) > 1 and s[1].strip() == 'Full_Composition_Exclusion':
        p = s[0].strip().split('..'); a = int(p[0],16); b = int(p[-1],16)
        excluded.update(range(a,b+1))
composition = sorted((v[0], v[1], k) for k,v in decomp.items() if len(v)==2 and k not in excluded)
fold = {}
for line in files['CaseFolding.txt'].decode().splitlines():
    s = line.split('#')[0].strip().split(';')
    if len(s)>2 and s[1].strip() in ('C','F'):
        fold[int(s[0],16)] = [int(x,16) for x in s[2].split()]
out = ['// Unicode 15.1.0; generated by tools/gen_unicode_tables.py.']
out += [f'// SHA-256 {n}: {hashlib.sha256(files[n]).hexdigest()}' for n in names]
def table(name, ty, rows):
    out.append(f'pub static {name}: &[{ty}] = &[')
    out.extend('    '+row+',' for row in rows); out.append('];')
table('ASSIGNED', '(u32, u32)', (f'(0x{a:X}, 0x{b:X})' for a,b in merged))
table('CCC', '(u32, u8)', (f'(0x{k:X}, {v})' for k,v in sorted(ccc.items())))
for name, data in [('DECOMP',decomp), ('FOLD',fold)]:
    table(name, '(u32, &[u32])', (f'(0x{k:X}, &[{", ".join(f"0x{x:X}" for x in v)}])' for k,v in sorted(data.items())))
table('COMPOSE', '(u32, u32, u32)', (f'(0x{a:X}, 0x{b:X}, 0x{c:X})' for a,b,c in composition))
pathlib.Path('kernel/src/unicode_tables.rs').write_text('\n'.join(out)+'\n', encoding='utf-8')
